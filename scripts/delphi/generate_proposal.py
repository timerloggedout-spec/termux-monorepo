"""Oracle Method proposal generator.

Owner correction (2026-10-27): proposals for competitions, RFPs,
provider-extension research, and like surfaces are GENERATED by the
Oracle Method system. The gate / ballot / weighting machinery is the
evaluation layer over what the system generates — not the product.

Pipeline: evidence set (the `fetch_evidence` schema — provenance- and
freshness-stamped items, see apps/weekend-challenge-delphi-oracle/) +
a structured brief -> a proposal in the repo's proposal format
(docs/proposals/: MANIFEST.md, ITEMS.md, RFP.md) plus a PROVENANCE.json
generation receipt.

Discipline:
- Deterministic rendering. No model calls, no ballots, nothing
  asserted beyond the brief and its evidence.
- Every brief point carries `evidence_refs` (claims in the evidence
  sets). A point whose refs do not resolve renders under
  "Unverified / open" — marked, never silently asserted or dropped.
- Facts are stamped: each generated document names the generator, the
  generation time, and the evidence-set hashes it was built from.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

GENERATOR = "scripts/delphi/generate_proposal.py"
VERSION = "oracle-method-generator/v1"
PROVENANCE_SCHEMA = "oracle-method-generation/v1"


def _canonical(value) -> bytes:
    return json.dumps(value, sort_keys=True).encode()


def _sha(value) -> str:
    return hashlib.sha256(_canonical(value)).hexdigest()


def evidence_index(evidence_sets: list[dict]) -> dict[str, dict]:
    """claim -> evidence item, across all supplied sets."""
    index: dict[str, dict] = {}
    for ev in evidence_sets:
        for item in ev.get("items", []):
            index.setdefault(item["claim"], item)
    return index


def _partition(points: list[dict], index: dict[str, dict]):
    evidenced, unverified = [], []
    for point in points:
        refs = point.get("evidence_refs", [])
        if refs and all(ref in index for ref in refs):
            evidenced.append(point)
        else:
            unverified.append(point)
    return evidenced, unverified


def _cite(point: dict, index: dict[str, dict]) -> str:
    refs = ", ".join(f"`{ref}`" for ref in point.get("evidence_refs", []))
    return f" (evidence: {refs})" if refs else ""


def render_manifest(brief: dict, evidence_sets: list[dict], generated_at: str) -> str:
    index = evidence_index(evidence_sets)
    evidenced, unverified = _partition(brief.get("summary_points", []), index)
    set_hashes = ", ".join(_sha(ev)[:12] for ev in evidence_sets)
    lines = [
        "---",
        f"id: {brief['id']}",
        f"title: \"{brief['title']}\"",
        "author: oracle-method",
        f"posted_at: {generated_at[:10]}",
        f"source: generated by {GENERATOR} {VERSION} from evidence sets [{set_hashes}]",
        "status: in_review",
        f"priority: {brief.get('priority', 'P1')}",
        "reviewers:",
        "  - id: timerloggedout-spec",
        "    role: operator-authorizer",
        "    status: requested",
        f"related_issues: {json.dumps(brief.get('related_issues', []))}",
        f"related_prs: {json.dumps(brief.get('related_prs', []))}",
        "gates_required: [proposal-lifecycle, repo-gate]",
        "---",
        "",
        f"# MANIFEST — {brief['id']}",
        "",
        "## Summary",
        "",
    ]
    for point in evidenced:
        lines.append(f"- {point['text']}{_cite(point, index)}")
    if unverified:
        lines += ["", "## Unverified / open", ""]
        for point in unverified:
            lines.append(f"- UNVERIFIED: {point['text']} (evidence refs unresolved at generation time)")
    lines += [
        "",
        "## Current state",
        "",
        f"- Generated {generated_at} by the Oracle Method generator ({VERSION}); "
        "no ballots, provider results, or external claims are asserted.",
        "- Independent review is requested; the Delphi gate evaluates this "
        "proposal through the same RFP process as any other.",
        "",
    ]
    return "\n".join(lines)


def render_items(brief: dict) -> str:
    prefix = brief.get("item_prefix", "GEN")
    lines = [f"# ITEMS — {brief['id']}", "",
             "| ID | Item | State | Evidence / exit condition |",
             "|---|---|---|---|"]
    for i, item in enumerate(brief.get("items", []), start=1):
        lines.append(f"| {prefix}-{i:03d} | {item['item']} | "
                     f"{item.get('state', 'proposed')} | {item.get('evidence', '')} |")
    lines.append("")
    return "\n".join(lines)


def render_rfp(brief: dict, evidence_sets: list[dict], generated_at: str) -> str:
    index = evidence_index(evidence_sets)
    evidenced, unverified = _partition(brief.get("summary_points", []), index)
    deadline = brief.get("deadline")
    deadline_line = (f"- **Deadline:** {deadline}"
                     if deadline and brief.get("deadline_evidence_refs")
                     and all(r in index for r in brief["deadline_evidence_refs"])
                     else "- **Deadline:** UNVERIFIED — confirm from the official page")
    lines = [
        f"# Proposal — {brief['title']}",
        "",
        f"- **Proposal ID:** {brief['id']}",
        f"- **Kind:** {brief.get('kind', 'research')}",
        f"- **Surface:** {brief.get('surface', 'UNVERIFIED')}",
        deadline_line,
        "- **Status:** GENERATED — in review; generated proposals carry no ballots",
        f"- **Generated:** {generated_at} by {GENERATOR} {VERSION}",
        "",
        "## 1. Executive request",
        "",
        brief.get("executive_request", ""),
        "",
        "## 2. Basis in evidence",
        "",
    ]
    for point in evidenced:
        lines.append(f"- {point['text']}{_cite(point, index)}")
    if unverified:
        lines += ["", "## 3. Unverified / open", ""]
        for point in unverified:
            lines.append(f"- UNVERIFIED: {point['text']}")
    lines += [
        "",
        "## Provenance",
        "",
        f"Generated from {len(evidence_sets)} evidence set(s), "
        f"{sum(len(ev.get('items', [])) for ev in evidence_sets)} stamped items. "
        "Full generation receipt: `PROVENANCE.json` in this directory. "
        "Facts not resolved against the evidence at generation time are "
        "marked UNVERIFIED above, never asserted.",
        "",
    ]
    return "\n".join(lines)


def generate(brief: dict, evidence_sets: list[dict],
             generated_at: str | None = None) -> dict[str, str]:
    generated_at = generated_at or datetime.now(timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%SZ")
    docs = {
        "MANIFEST.md": render_manifest(brief, evidence_sets, generated_at),
        "ITEMS.md": render_items(brief),
        "RFP.md": render_rfp(brief, evidence_sets, generated_at),
    }
    provenance = {
        "schema": PROVENANCE_SCHEMA,
        "generator": f"{GENERATOR} {VERSION}",
        "generated_at": generated_at,
        "proposal_id": brief["id"],
        "author": "oracle-method",
        "evidence_sets": [{"sha256": _sha(ev), "items": len(ev.get("items", [])),
                           "assembled_at": ev.get("assembled_at")}
                          for ev in evidence_sets],
        "documents": {name: hashlib.sha256(text.encode()).hexdigest()
                      for name, text in docs.items()},
        "human_ballots_received": 0,
        "external_calls_by_generator": 0,
    }
    docs["PROVENANCE.json"] = json.dumps(provenance, indent=2) + "\n"
    return docs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Oracle Method proposal generator")
    parser.add_argument("--brief", required=True, help="brief JSON path")
    parser.add_argument("--evidence", action="append", default=[],
                        help="evidence-set JSON path (repeatable)")
    parser.add_argument("--out", required=True, help="output directory")
    args = parser.parse_args(argv)

    brief = json.loads(Path(args.brief).read_text())
    evidence_sets = [json.loads(Path(p).read_text()) for p in args.evidence]
    docs = generate(brief, evidence_sets)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, text in docs.items():
        (out / name).write_text(text)
    print(f"generated {brief['id']}: {', '.join(docs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
