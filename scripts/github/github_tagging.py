def snapshot_hash(payload: dict[str, Any]) -> str:
    body = {k: v for k, v in payload.items() if k not in ("generated_at", "snapshot_hash")}
    return hashlib.sha256(json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")).hexdigest()


def build_harvest_matrix(repos: list[dict[str, Any]]) -> dict[str, Any]:
    cells: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for rec in repos:
        pri = rec.get("priority") or "P?"
        for d in rec.get("domain") or ["devex"]:
            cells[pri][d] += 1
    matrix = {p: dict(sorted(domains.items(), key=lambda x: -x[1])) for p, domains in sorted(cells.items())}
    return {"axes": {"row": "priority", "col": "domain"}, "cells": matrix, "p0_domains": matrix.get("P0", {}), "p1_domains": matrix.get("P1", {})}


