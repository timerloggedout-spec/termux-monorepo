def maybe_merge_observatory(repos: list[dict[str, Any]], observatory_path: Path | None) -> list[dict[str, Any]]:
    if not observatory_path or not observatory_path.exists():
        return repos
    try:
        data = json.loads(observatory_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return repos
    by_name = {r.get("full_name"): r for r in repos if r.get("full_name")}
    for rec in data.get("repositories") or []:
        fn = rec.get("full_name")
        if not fn or fn not in by_name:
            continue
        by_name[fn]["observatory_provenance"] = rec.get("provenance") or []
        by_name[fn]["observatory_domains"] = (rec.get("classification") or {}).get("domains") or []
    return list(by_name.values()) if by_name else repos


def write_csv(path: Path, records: list[dict[str, Any]]) -> None:
    fields = ["name", "full_name", "html_url", "relationship", "priority", "intent", "language_family", "type", "domain", "tags_flat", "fork", "archived", "language", "description", "updated_at", "upstream", "provenance"]
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        for rec in records:
            row = dict(rec)
            row["type"] = "|".join(rec.get("type") or [])
            row["domain"] = "|".join(rec.get("domain") or [])
            row["provenance"] = "|".join(rec.get("provenance") or [])
            w.writerow(row)


def write_summary_md(path: Path, export: dict[str, Any]) -> None:
    repos = export.get("repos") or []
    p0 = [r for r in repos if r.get("priority") == "P0"]
    keep = [r for r in repos if r.get("intent") == "keep-active"]
    matrix = export.get("harvest_matrix") or {}
    lines = ["# GitHub multi-category tagging (generated)", "", f"Generated: `{export.get('generated_at')}`", f"Snapshot: `{export.get('snapshot_hash', '')[:12]}`", f"Owned indexed: **{export.get('repos_indexed', 0)}** · Stars sample: **{export.get('stars_indexed', 0)}**", "", "## Stats", "", f"- Priority: `{export.get('stats', {}).get('by_priority')}`", f"- Intent: `{export.get('stats', {}).get('by_intent')}`", f"- Top domains: `{export.get('stats', {}).get('by_domain_top')}`", "", "## Harvest matrix (priority × domain)", "", "```json", json.dumps(matrix.get("cells") or {}, indent=2)[:4000], "```", "", "## P0", ""]
    for r in p0:
        lines.append(f"- **{r['name']}** — {', '.join(r.get('type') or [])} · {r.get('intent')} · {', '.join(r.get('domain') or [])}")
    lines.extend(["", "## Keep-active", ""])
    for r in keep:
        lines.append(f"- `{r['name']}` — {r.get('priority')} · {', '.join((r.get('type') or [])[:3])}")
    lines.extend(["", "## Related boards (KEEP SEPARATE)", "", "- Lane matrix: `docs/ops/generated/lane-matrix-status.md`", "- Observatory index: `workspace/llm_map/repositories/repository-index.json`", "- This filter surface: `docs/ops/generated/github-tagging/`", "", "> Autogenerated by `scripts/github/github_tagging.py` via `github-tagging-refresh`.", "> Do not hand-edit; change rules in the script and let cron regenerate.", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def build_export(owned_raw: list[dict[str, Any]], starred_raw: list[dict[str, Any]], owner: str) -> dict[str, Any]:
    repos = [normalize_owned(r) for r in owned_raw if (r.get("owner") or {}).get("login") == owner or r.get("full_name", "").startswith(f"{owner}/")]
    if not repos:
        repos = [normalize_owned(r) for r in owned_raw]
    stars = [normalize_starred(r) for r in starred_raw]
    by_priority: dict[str, int] = defaultdict(int)
    by_intent: dict[str, int] = defaultdict(int)
    by_domain: dict[str, int] = defaultdict(int)
    for rec in repos:
        by_priority[rec["priority"]] += 1
        by_intent[rec["intent"]] += 1
        for d in rec["domain"]:
            by_domain[d] += 1
    export: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION, "builder": "termux-monorepo.github_tagging@1.1", "account": owner,
        "generated_at": now(), "repos_indexed": len(repos), "stars_indexed": len(stars),
        "stats": {"by_priority": dict(sorted(by_priority.items())), "by_intent": dict(sorted(by_intent.items(), key=lambda x: -x[1])), "by_domain_top": dict(sorted(by_domain.items(), key=lambda x: -x[1])[:20])},
        "harvest_matrix": build_harvest_matrix(repos), "taxonomy": taxonomy(),
        "repos": sorted(repos, key=lambda r: (r.get("priority") or "P9", r.get("name") or "")),
        "stars_sample": stars[:200],
    }
    export["snapshot_hash"] = snapshot_hash(export)
    return export


def main(argv: list[str] | None = None, fetch: Callable[..., Any] = get_json) -> int:
    parser = argparse.ArgumentParser(description="Multi-category GitHub tagging (autogenerated artifacts)")
    parser.add_argument("--owner", required=True)
    parser.add_argument("--out-dir", type=Path, default=Path("docs/ops/generated/github-tagging"))
    parser.add_argument("--token-env", default="GITHUB_TAGGING_TOKEN")
    parser.add_argument("--max-star-pages", type=int, default=8)
    parser.add_argument("--observatory-index", type=Path, default=Path("workspace/llm_map/repositories/repository-index.json"))
    args = parser.parse_args(argv)
    token = os.environ.get(args.token_env) or os.environ.get("GITHUB_TOKEN") or os.environ.get("REPOSITORY_OBSERVATORY_TOKEN")
    if not token:
        print(f"missing {args.token_env} or GITHUB_TOKEN", file=sys.stderr)
        return 2
    me = fetch("/user", token)
    login = me.get("login") if isinstance(me, dict) else None
    if login != args.owner:
        raise RuntimeError(f"authenticated GitHub user is {login!r}, expected {args.owner!r}")
    owned = pages("/user/repos", token, {"affiliation": "owner", "sort": "updated", "direction": "desc"}, fetch=fetch)
    starred: list[dict[str, Any]] = []
    for page in range(1, args.max_star_pages + 1):
        payload = fetch("/user/starred", token, {"sort": "updated", "direction": "desc", "per_page": 100, "page": page})
        if not isinstance(payload, list):
            raise RuntimeError("expected list from /user/starred")
        starred.extend(x for x in payload if isinstance(x, dict))
        if len(payload) < 100:
            break
    export = build_export(owned, starred, args.owner)
    export["repos"] = maybe_merge_observatory(export["repos"], args.observatory_index)
    export["repos_indexed"] = len(export["repos"])
    export["harvest_matrix"] = build_harvest_matrix(export["repos"])
    export["snapshot_hash"] = snapshot_hash(export)
    out = args.out_dir
    out.mkdir(parents=True, exist_ok=True)
    (out / "taxonomy.json").write_text(json.dumps(export["taxonomy"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (out / "repos_tagged.json").write_text(json.dumps(export, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    write_csv(out / "repos_tagged.csv", export["repos"])
    write_summary_md(out / "TAGGING-SUMMARY.md", export)
    (out / "stars_tagged_sample.json").write_text(json.dumps({"count": len(export["stars_sample"]), "stars": export["stars_sample"]}, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (out / "visibility-board.json").write_text(json.dumps(build_visibility_board(export), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (out / "harvest-matrix.json").write_text(json.dumps(export["harvest_matrix"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"repos_indexed": export["repos_indexed"], "stars_indexed": export["stars_indexed"], "snapshot_hash": export["snapshot_hash"][:12], "by_priority": export["stats"]["by_priority"], "p0_domains": export["harvest_matrix"].get("p0_domains")}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
