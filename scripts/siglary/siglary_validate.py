#!/usr/bin/env python3
"""Deterministic Siglary conformance gate. Principle-⑤ ambiguity remains EST."""
from __future__ import annotations
import argparse, hashlib, json, re, subprocess, sys, time, unicodedata
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
MATRICE = "docs/proposals/active/notation-sets/CAVEMAN-MICRO-DENSE-V2.md"
GLYPH_FILE = "scripts/siglary/issued_glyphs.json"
DATA_EXT = {".json", ".jsonl", ".ndjson", ".yaml", ".yml"}
STATUS = re.compile(r"^\s*(?:state|verdict|outcome|status)\s*[:=]\s*\S", re.I)
RECEIPT = re.compile(r"(?:🧾|https?://\S+|\b(?:PR|issue|run)\s*#?\d+\b|\b[0-9a-f]{7,40}\b|\breceipt\s*[:=])", re.I)
CHORD = re.compile(r"\bchord\s*[:=]\s*([a-z][a-z0-9]{1,5})\b", re.I)
GLYPH = re.compile(r"\bglyph\s*[:=]\s*([^\s,;.!?]+)", re.I)
OPERATOR = re.compile(r"\boperator\s*[:=]\s*([^\s,;.!?]+)", re.I)
DOMAIN = re.compile(r"\b(shorthand_[a-z0-9_]+)\b", re.I)
OPERATORS = {"∧", "¬", "∨", "⇒", "∀", "∃", "∅", "∈", "∆", "++", "≅"}
MISUSE = [
    re.compile(r"\boperators?\s+(?:are|as|called|classified as)\s+(?:a\s+)?glyphs?\b", re.I),
    re.compile(r"\bchords?\s+(?:are|as|called|classified as)\s+(?:a\s+)?glyphs?\b", re.I),
    re.compile(r"\b(?:glyph|glyphs)\s+(?:include|includes|are|means)\s+[^\n.]*[∧¬∨⇒∀∃∅∈∆≅]", re.I),
]


def paths_in_repo(root: Path) -> list[str]:
    if (root / ".git").exists():
        out = subprocess.run(["git", "ls-files", "-z"], cwd=root, check=True, capture_output=True).stdout
        return [p.decode("utf-8", "surrogateescape") for p in out.split(b"\0") if p]
    return [p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()]


def changed_paths(root: Path, base: str) -> set[str]:
    out = subprocess.run(["git", "diff", "--name-only", "-z", f"{base}...HEAD"], cwd=root, check=True, capture_output=True).stdout
    return {p.decode("utf-8", "surrogateescape") for p in out.split(b"\0") if p}


def load_glyphs(path: Path) -> set[str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    source = data.get("source", {})
    if data.get("schema") != "siglary-issued-glyphs/v1" or not all(source.get(k) for k in ("path", "section", "source_commit")):
        raise ValueError("issued glyph registry lacks its schema or provenance")
    glyphs = data.get("glyphs", [])
    if not glyphs or len(glyphs) != len(set(glyphs)):
        raise ValueError("issued glyphs must be non-empty and unique")
    return set(glyphs)


def load_domains(root: Path) -> dict[str, set[str]]:
    file = root / MATRICE
    if not file.is_file():
        raise FileNotFoundError(MATRICE)
    result: dict[str, set[str]] = defaultdict(set)
    active, table = None, False
    for original in file.read_text(encoding="utf-8").splitlines():
        line = original.replace(chr(96), "")
        head = re.match(r"^### .*\((shorthand_[a-z0-9_]+)\)", line)
        if head:
            active, table = head.group(1), False
        elif line.startswith("### "):
            active, table = None, False
        elif active and line.startswith("| Chord"):
            table = True
        elif active and table:
            row = re.match(r"^\|\s*([a-z][a-z0-9]{1,5})\s*\|", line)
            if row:
                result[active].add(row.group(1))
            elif not line.startswith("|"):
                table = False
    if not result:
        raise ValueError("no Shorthand Domain tables found")
    return dict(result)


def exemption(path: str, text: str) -> str | None:
    p = path.replace("\\", "/").lower()
    if re.search(r"(^|/)ops/.*/(?:ledger|cycle-ledger|hash-chain)[^/]*\.jsonl?$", p): return "E1"
    if "/fixtures/" in p or p.startswith("tests/fixtures/") or "SIGLARY-FIXTURE:" in text: return "E4"
    head = "\n".join(text.splitlines()[:20]).lower()
    if "/generated/" in p or p.startswith("docs/ops/generated/") or "generated by" in head or "@generated" in head: return "E5"
    if any(x in p for x in ("/chat-export/", "/chat-exports/", "/chat-transcripts/", "/transcripts/", "/session_store/")): return "E6"
    if re.search(r"(?im)^\s*(?:<!--\s*)?SIGLARY-EXEMPT:\s*E[1-6]\s*(?:—|-)\s*\S+", text): return "DECLARED"
    return None


def data_findings(text: str, path: str) -> list[dict[str, Any]]:
    findings = []
    def walk(value: Any, loc: str = "$", line: int | None = None):
        if isinstance(value, str) and value.strip() in {"N∅", "NOT_ESTABLISHED"}:
            findings.append({"path": path, "rule": "N-IN-DATA", "severity": "HARD", "line": line, "message": f"chat-only marker stored as data at {loc}"})
        elif isinstance(value, dict):
            for key, item in value.items(): walk(item, f"{loc}.{key}", line)
        elif isinstance(value, list):
            for i, item in enumerate(value): walk(item, f"{loc}[{i}]", line)
    suffix = Path(path).suffix.lower()
    if suffix == ".json":
        try: walk(json.loads(text))
        except json.JSONDecodeError: pass
    elif suffix in {".jsonl", ".ndjson"}:
        for n, line in enumerate(text.splitlines(), 1):
            try: walk(json.loads(line), "$", n)
            except json.JSONDecodeError: pass
    else:
        for n, line in enumerate(text.splitlines(), 1):
            if re.match(r"^\s*(?:-\s*)?(?:[^:#]+:\s*)?['\"]?(?:N∅|NOT_ESTABLISHED)['\"]?\s*(?:#.*)?$", line):
                findings.append({"path": path, "rule": "N-IN-DATA", "severity": "HARD", "line": n, "message": "chat-only marker stored as a YAML scalar"})
    return findings


data_value_findings = data_findings


def structured_receipt_findings(text: str, path: str) -> list[dict[str, Any]]:
    findings = []
    receipt_keys = {"receipt", "receipt_id", "evidence_url", "source_url", "run_url", "url", "commit_sha", "source_ref", "issue_url"}
    status_keys = {"state", "status", "verdict", "outcome"}
    def walk(value: Any, loc: str = "$", line: int | None = None):
        if isinstance(value, dict):
            keys = {str(k).lower() for k in value}
            if keys & status_keys and not any(value.get(k) for k in value if str(k).lower() in receipt_keys):
                findings.append({"path": path, "rule": "RECEIPT-ADJACENCY", "severity": "HARD", "line": line, "message": f"DoE record at {loc} has a state/verdict without a receipt reference"})
            for key, item in value.items(): walk(item, f"{loc}.{key}", line)
        elif isinstance(value, list):
            for i, item in enumerate(value): walk(item, f"{loc}[{i}]", line)
    suffix = Path(path).suffix.lower()
    if suffix == ".json":
        try: walk(json.loads(text))
        except json.JSONDecodeError: pass
    elif suffix in {".jsonl", ".ndjson"}:
        for n, line in enumerate(text.splitlines(), 1):
            try: walk(json.loads(line), "$", n)
            except json.JSONDecodeError: pass
    return findings


def data_blocks(text: str, path: str) -> list[dict[str, Any]]:
    marker = chr(96) * 3
    findings, active, lang, body = [], False, "", []
    for line in text.splitlines():
        if line.lstrip().startswith(marker):
            if not active:
                lang = line.strip()[3:].strip().lower().split()[0] if line.strip()[3:].strip() else ""
                active, body = lang in {"json", "jsonl", "ndjson", "yaml", "yml"}, []
            else:
                if active:
                    ext = ".json" if lang == "json" else (".jsonl" if lang in {"jsonl", "ndjson"} else ".yaml")
                    findings.extend(data_findings("\n".join(body), path + ext))
                active, body = False, []
        elif active:
            body.append(line)
    return findings


def visible_lines(text: str) -> list[tuple[int, str]]:
    out, active, fence = [], False, ""
    marker = chr(96) * 3
    for n, line in enumerate(text.splitlines(), 1):
        s = line.lstrip()
        if s.startswith(marker) or s.startswith("~~~"):
            mark = s[:3]
            if not active: active, fence = True, mark
            elif mark == fence: active = False
            continue
        if active or s.startswith(">") or re.match(r"^\s*(?:<!--\s*)?SIGLARY-EXEMPT:\s*E[1-6]", line): continue
        out.append((n, line))
    return out


def glyph_clusters(line: str) -> list[str]:
    out, cur, join = [], "", False
    for ch in line:
        cat = unicodedata.category(ch)
        mark = ch in {"\ufe0e", "\ufe0f", "\u200d"} or cat in {"Mn", "Mc"}
        symbol = cat == "So"
        if ch == "\u200d" and cur: cur += ch; join = True
        elif symbol:
            if join and cur: cur += ch
            elif cur == "⚖" and ch == "✓": cur += ch
            else:
                if cur: out.append(cur)
                cur = ch
            join = False
        elif (mark and cur) or (0x1F3FB <= ord(ch) <= 0x1F3FF and cur): cur += ch
        else:
            if cur: out.append(cur)
            cur, join = "", False
    if cur: out.append(cur)
    return out


def text_findings(text: str, path: str, kind: str, glyphs: set[str], domains: dict[str, set[str]]) -> list[dict[str, Any]]:
    found, lines = [], visible_lines(text)
    for i, (n, line) in enumerate(lines):
        check = "" if "Working title" in line or "Caveman Micro Dense" in line else line
        for glyph in glyph_clusters(check):
            if glyph not in glyphs: found.append({"path": path, "rule": "UNISSUED-GLYPH", "severity": "HARD", "line": n, "message": f"unissued pictograph {glyph}"})
        if any(p.search(line) for p in MISUSE): found.append({"path": path, "rule": "CLASS-MISUSE", "severity": "HARD", "line": n, "message": "keep GLYPHS, CHORDS and OPERATORS distinct"})
        plain = line.replace(chr(96), "")
        for m in GLYPH.finditer(plain):
            if m.group(1) not in glyphs: found.append({"path": path, "rule": "UNISSUED-GLYPH", "severity": "HARD", "line": n, "message": f"glyph {m.group(1)} is not issued"})
        for m in OPERATOR.finditer(plain):
            if m.group(1) not in OPERATORS: found.append({"path": path, "rule": "UNREGISTERED-OPERATOR", "severity": "HARD", "line": n, "message": f"operator {m.group(1)} is not registered"})
        for m in CHORD.finditer(plain):
            d = DOMAIN.search(plain)
            if not d or m.group(1) not in domains.get(d.group(1), set()): found.append({"path": path, "rule": "UNRESOLVED-CHORD", "severity": "HARD", "line": n, "message": f"chord {m.group(1)} lacks a matching named domain"})
        if kind in {"github_collaboration", "doe_participant"} and STATUS.match(line):
            adjacent = line + ("\n" + lines[i + 1][1] if i + 1 < len(lines) else "")
            if not RECEIPT.search(adjacent): found.append({"path": path, "rule": "RECEIPT-ADJACENCY", "severity": "HARD", "line": n, "message": "state/verdict requires an adjacent receipt reference"})
        if "SIGLARY-FLAG:" in line: found.append({"path": path, "rule": "PRINCIPLE-5-SUSPENDED", "severity": "EST", "line": n, "message": "pending Linguist ruling; expand to plain form"})
    return found


def surface_kind(path: str) -> str | None:
    p, name = path.replace("\\", "/"), Path(path).name
    if name == "CLAUDE.md": return "claude"
    if name in {"SKILL.md", "SKILLS.md"} or name.endswith(".SKILLS") or p.startswith(("skills/", ".agents/skills/", ".github/skills/")): return "skills"
    if p.startswith("docs/icm/"): return "icm"
    if p.startswith(("ops/doe/", "ops/que/dispatch/", "docs/ops/doe/")): return "doe_participant"
    if p in {"docs/proposals/active/notation-sets/SIGLARY-STANDARD.md", MATRICE}: return "standard"
    if Path(p).suffix.lower() in DATA_EXT: return "data"
    return None


def event_surfaces(event: dict, name: str) -> list[tuple[str, str, str]]:
    e, out = event, []
    def add(kind, label, text):
        if text: out.append((kind, label, text))
    if name == "pull_request":
        x=e.get("pull_request",{}); add("github_collaboration","pull_request.title",x.get("title","")); add("github_collaboration","pull_request.body",x.get("body",""))
    elif name == "issues":
        x=e.get("issue",{}); add("github_collaboration","issue.title",x.get("title","")); add("github_collaboration","issue.body",x.get("body",""))
    elif name in {"issue_comment","discussion_comment","pull_request_review_comment","commit_comment"}: add("github_collaboration",name+".body",e.get("comment",{}).get("body",""))
    elif name == "pull_request_review": add("github_collaboration",name+".body",e.get("review",{}).get("body",""))
    elif name == "release":
        x=e.get("release",{}); add("github_collaboration","release.name",x.get("name","")); add("github_collaboration","release.body",x.get("body",""))
    elif name == "discussion":
        x=e.get("discussion",{}); add("github_collaboration","discussion.title",x.get("title","")); add("github_collaboration","discussion.body",x.get("body",""))
    return out


def census(root: Path, paths: list[str], event: dict | None = None, event_name: str = "") -> dict:
    start, glyphs = time.perf_counter(), load_glyphs(root / GLYPH_FILE)
    domains = load_domains(root)
    classes, findings = defaultdict(lambda: {"surfaces_scanned":0,"compliant":0,"soft_violations":0,"hard_violations":0}), []
    for rel in sorted(set(paths)):
        file=root/rel
        if not file.is_file(): continue
        try: text=file.read_text(encoding="utf-8")
        except (UnicodeDecodeError,OSError): continue
        if exemption(rel,text): continue
        kind=surface_kind(rel)
        if not kind: continue
        if kind == "data" or (kind == "doe_participant" and Path(rel).suffix.lower() in DATA_EXT):
            current = data_findings(text,rel)
            if kind == "doe_participant": current.extend(structured_receipt_findings(text,rel))
        else:
            current = text_findings(text,rel,kind,glyphs,domains)
        if kind == "skills": current.extend(data_blocks(text,rel))
        if kind == "claude" and not re.search(r"SIGLARY-STANDARD\.md|Siglary",text,re.I): current.append({"path":rel,"rule":"CLAUDE-REFERENCE","severity":"HARD","line":None,"message":"CLAUDE.md must reference the canonical Siglary standard"})
        classes[kind]["surfaces_scanned"] += 1
        if current: findings.extend(current)
        else: classes[kind]["compliant"] += 1
        for f in current:
            if f["severity"] == "HARD": classes[kind]["hard_violations"] += 1
            elif f["severity"] == "SOFT": classes[kind]["soft_violations"] += 1
    for kind,label,content in event_surfaces(event or {},event_name):
        current=text_findings(content,label,kind,glyphs,domains); classes[kind]["surfaces_scanned"]+=1; findings.extend(current)
        if not current: classes[kind]["compliant"]+=1
        for f in current:
            if f["severity"] == "HARD": classes[kind]["hard_violations"]+=1
            elif f["severity"] == "SOFT": classes[kind]["soft_violations"]+=1
    total=sum(x["surfaces_scanned"] for x in classes.values()); hard=sum(x["hard_violations"] for x in classes.values()); soft=sum(x["soft_violations"] for x in classes.values())
    for x in classes.values(): x["compliance_rate"]=(x["compliant"]/x["surfaces_scanned"]) if x["surfaces_scanned"] else None
    return {"schema":"siglary-census/v1","state":"INCONCLUSIVE" if total==0 else ("FAIL" if hard else "PASS"),"surfaces_scanned":total,"hard_violations":hard,"soft_violations":soft,"surface_classes":dict(sorted(classes.items())),"violations":findings,"performance":{"runtime_seconds":round(time.perf_counter()-start,6),"characters_scanned":sum(len((root/p).read_text(encoding="utf-8",errors="ignore")) for p in set(paths) if (root/p).is_file()),"files_considered":len(set(paths))}}


def receipt_id(event: dict, event_name: str, report: dict) -> str:
    raw=json.dumps({"event_name":event_name,"event":event,"state":report["state"],"violations":report["violations"]},sort_keys=True,separators=(",",":"),ensure_ascii=False)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def append_feed(path: Path, receipt: dict) -> bool:
    path.parent.mkdir(parents=True,exist_ok=True); seen=set()
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            try: seen.add(json.loads(line).get("receipt_id",""))
            except json.JSONDecodeError: pass
    if receipt["receipt_id"] in seen: return False
    with path.open("a",encoding="utf-8") as f: f.write(json.dumps(receipt,sort_keys=True,ensure_ascii=False)+"\n")
    return True


def main(argv=None) -> int:
    p=argparse.ArgumentParser(description=__doc__); p.add_argument("--root",type=Path,default=ROOT); p.add_argument("--changed-from"); p.add_argument("--event-only",action="store_true"); p.add_argument("--event-file",type=Path); p.add_argument("--event-name",default=""); p.add_argument("--report",type=Path); p.add_argument("--feed",type=Path); a=p.parse_args(argv)
    root=a.root.resolve(); paths=[] if a.event_only else paths_in_repo(root)
    if a.changed_from: paths=sorted(set(paths)&changed_paths(root,a.changed_from))
    event=json.loads(a.event_file.read_text(encoding="utf-8")) if a.event_file and a.event_file.is_file() else {}
    report=census(root,paths,event,a.event_name)
    if event or a.event_name: report["receipt_id"]=receipt_id(event,a.event_name,report)
    if a.feed:
        entry={"schema":"siglary_compliance/v1","receipt_id":report.get("receipt_id") or receipt_id(event,a.event_name,report),"state":report["state"],"surfaces_scanned":report["surfaces_scanned"],"hard_violations":report["hard_violations"],"soft_violations":report["soft_violations"],"surface_classes":report["surface_classes"],"runtime_seconds":report["performance"]["runtime_seconds"]}
        report["feed_appended"]=append_feed(a.feed,entry)
    encoded=json.dumps(report,indent=2,sort_keys=True,ensure_ascii=False)+"\n"
    if a.report: a.report.parent.mkdir(parents=True,exist_ok=True); a.report.write_text(encoded,encoding="utf-8")
    print(encoded,end="")
    if report["state"] == "INCONCLUSIVE": print("INCONCLUSIVE: zero surfaces scanned; empty census is not PASS",file=sys.stderr); return 2
    if report["state"] == "FAIL": print(f"FAIL: {report['hard_violations']} HARD violation(s)",file=sys.stderr); return 1
    print("PASS",file=sys.stderr); return 0

if __name__ == "__main__": raise SystemExit(main())
