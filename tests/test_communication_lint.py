"""Regression coverage for DO-first communication lint."""
from __future__ import annotations
import unittest
from scripts.ci.communication_lint import scan_text

class CommunicationLintTests(unittest.TestCase):
    def test_affirmative_do_statement_passes(self):
        text = "DO route the request to QUE when admission succeeds.\n"
        self.assertEqual(scan_text(text, "docs/guide.md"), [])

    def test_negative_prose_produces_machine_finding(self):
        findings = scan_text("Do not commit credentials.\n", "docs/guide.md")
        self.assertEqual(len(findings), 1)
        self.assertEqual(findings[0]["line"], 1)
        self.assertIn("affirmative action", findings[0]["suggestion"])

    def test_quoted_code_and_inline_code_are_excluded(self):
        text = (
            "> Do not copy this quoted source.\n"
            "```text\nNever run this example.\n```\n"
            "Use not_ready as the exact state identifier.\n"
            "Proceed with the verified result.\n"
        )
        self.assertEqual(scan_text(text, "docs/guide.md"), [])

    def test_allowlisted_technical_terms_pass(self):
        text = "NO-GO remains the exact disposition; no-cost and not_found are identifiers.\n"
        self.assertEqual(scan_text(text, "docs/guide.md"), [])

    def test_identifiers_and_multilingual_text_pass(self):
        text = "is_not_ready and notFound are identifiers; 状態を確認して実行します。\n"
        self.assertEqual(scan_text(text, "docs/guide.md"), [])

    def test_code_files_scan_comments_only(self):
        text = "message = \"Do not rewrite this runtime string.\"\n# Do not store tokens.\n"
        findings = scan_text(text, "scripts/example.py")
        self.assertEqual(len(findings), 1)

    def test_pr_metadata_is_scanned_as_prose(self):
        findings = scan_text("No fallback without quota proof.\n", "<PR title>")
        self.assertEqual(len(findings), 1)

    def test_authored_html_comments_are_linted(self):
        findings = scan_text("<!-- Do not bypass review. -->\\n", "docs/guide.md")
        self.assertEqual(len(findings), 2)

    def test_generated_projection_is_skipped(self):
        text = "<!-- LinguistProjection: generated -->\nDo not edit this file.\n"
        self.assertEqual(scan_text(text, "CLAUDE.md"), [])

if __name__ == "__main__":
    unittest.main()
